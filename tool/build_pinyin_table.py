"""Builds lib/core/pinyin_table.dart from the output of gen_pinyin.swift.

Usage: python3 -I tool/build_pinyin_table.py pinyin.txt > lib/core/pinyin_table.dart

Layout: `pinyinSyllables` lists the distinct toneless syllables; `pinyinCodes`
holds two ASCII characters (base 64, '0'..'o') per code point from U+4E00,
giving the syllable index + 1 (0 = no reading).
"""
import sys

FIRST = 0x4E00
LAST = 0x9FFF

readings = {}
with open(sys.argv[1], encoding="utf-8") as f:
    for line in f:
        cp, py = line.split()
        readings.setdefault(int(cp, 16), py)

syllables = sorted(set(readings.values()))
index = {s: i + 1 for i, s in enumerate(syllables)}
assert len(syllables) < 64 * 64

def b64(v):
    return chr(48 + v)

codes = []
for cp in range(FIRST, LAST + 1):
    v = index.get(readings.get(cp), 0)
    codes.append(b64(v >> 6) + b64(v & 63))
text = "".join(codes)
assert "'" not in text and "$" not in text

print("// GENERATED by tool/build_pinyin_table.py - do not edit.")
print("// Source: macOS Mandarin-Latin transform (tool/gen_pinyin.swift),")
print("// one reading per character for U+4E00..U+9FFF.")
print()
print("/// Distinct toneless pinyin syllables; codes below are 1-based indices.")
print("const pinyinSyllables = <String>[")
line = "  "
for s in syllables:
    item = "'" + s + "', "
    if len(line) + len(item) > 78:
        print(line.rstrip())
        line = "  "
    line += item
print(line.rstrip())
print("];")
print()
print("/// Two characters per code point starting at U+4E00 (base 64, offset 48).")
print("const pinyinCodes =")
chunks = [text[i:i + 100] for i in range(0, len(text), 100)]
for i, c in enumerate(chunks):
    end = ";" if i == len(chunks) - 1 else ""
    print("    r'" + c + "'" + end)
